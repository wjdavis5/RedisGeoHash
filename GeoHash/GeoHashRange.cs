namespace GeoHash
{
    /// <summary>
    /// Represents a range with minimum and maximum values.
    /// </summary>
    public struct GeoHashRange
    {
        /// <summary>
        /// The minimum value of the range.
        /// </summary>
        public double Min;
        
        /// <summary>
        /// The maximum value of the range.
        /// </summary>
        public double Max;
    }
}