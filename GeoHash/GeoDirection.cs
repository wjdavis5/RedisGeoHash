namespace GeoHash
{
    /// <summary>
    /// Represents the eight cardinal and intercardinal directions for GeoHash navigation.
    /// </summary>
    public enum GeoDirection
    {
        /// <summary>
        /// North direction.
        /// </summary>
        GeohashNorth = 0,
        
        /// <summary>
        /// East direction.
        /// </summary>
        GeohashEast,
        
        /// <summary>
        /// West direction.
        /// </summary>
        GeohashWest,
        
        /// <summary>
        /// South direction.
        /// </summary>
        GeohashSouth,
        
        /// <summary>
        /// Southwest direction.
        /// </summary>
        GeohashSouthWest,
        
        /// <summary>
        /// Southeast direction.
        /// </summary>
        GeohashSouthEast,
        
        /// <summary>
        /// Northwest direction.
        /// </summary>
        GeohashNorthWest,
        
        /// <summary>
        /// Northeast direction.
        /// </summary>
        GeohashNorthEast
    }
}